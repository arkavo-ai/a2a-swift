    public var status: TaskStatus
    /// Metadata associated with the task update.
    public var metadata: [String: JSONValue]?

    public init(
        taskId: String,
        contextId: String,
        status: TaskStatus,
        metadata: [String: JSONValue]? = nil
    ) {
        self.taskId = taskId
        self.contextId = contextId
        self.status = status
        self.metadata = metadata
    }
}

/// A task delta where an artifact has been generated (`lf.a2a.v1.TaskArtifactUpdateEvent`).
public struct TaskArtifactUpdateEvent: Sendable, Codable, Equatable {
    /// The ID of the task for this artifact.
    public var taskId: String
    /// The ID of the context that this task belongs to.
    public var contextId: String
    /// The artifact that was generated or updated.
    public var artifact: Artifact
    /// If true, the content should be appended to a previously sent artifact with the same ID.
    public var append: Bool
    /// If true, this is the final chunk of the artifact.
    public var lastChunk: Bool
    /// Metadata associated with the artifact update.
    public var metadata: [String: JSONValue]?

    public init(
        taskId: String,
        contextId: String,
        artifact: Artifact,
        append: Bool = false,
        lastChunk: Bool = false,
        metadata: [String: JSONValue]? = nil
    ) {
        self.taskId = taskId
        self.contextId = contextId
        self.artifact = artifact
        self.append = append
        self.lastChunk = lastChunk
        self.metadata = metadata
    }

    private enum CodingKeys: String, CodingKey {
        case taskId, contextId, artifact, append, lastChunk, metadata
    }

    public init(from decoder: any Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        taskId = try container.decode(String.self, forKey: .taskId)
        contextId = try container.decode(String.self, forKey: .contextId)
        artifact = try container.decode(Artifact.self, forKey: .artifact)
        append = try container.decodeIfPresent(Bool.self, forKey: .append) ?? false
        lastChunk = try container.decodeIfPresent(Bool.self, forKey: .lastChunk) ?? false
        metadata = try container.decodeIfPresent([String: JSONValue].self, forKey: .metadata)
    }

    public func encode(to encoder: any Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)
        try container.encode(taskId, forKey: .taskId)
        try container.encode(contextId, forKey: .contextId)
        try container.encode(artifact, forKey: .artifact)
        if append {
            try container.encode(append, forKey: .append)
        }
        if lastChunk {
            try container.encode(lastChunk, forKey: .lastChunk)
        }
        try container.encodeIfPresent(metadata, forKey: .metadata)
    }
}
